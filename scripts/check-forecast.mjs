import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import ts from 'typescript';
const source = await fs.readFile(new URL('../src/lib/forecast.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { estimateForecast, forecastWindows, formatForecastPercent } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const DAY = 86400000;
const now = Date.parse('2026-10-08T12:00:00+08:00');
const points = Array.from({ length: 366 }, (_, i) => ({ date: new Date(Date.parse('2025-10-08') + i * DAY).toISOString().slice(0, 10), rate: 300 }));
const low = estimateForecast(points, 299, [], now);
const high = estimateForecast(points, 301, [], now);
assert.ok(low.windows.every(w => w.percent === 100));
assert.ok(high.windows.every(w => w.percent === 0));
assert.deepEqual(estimateForecast([...points, { date: '2026-10-09', rate: 900 }], 301, [], now), high, 'Future observations must not enter the model.');
assert.deepEqual(estimateForecast(points, 301, [], now), high, 'Repeated inputs must be deterministic.');
assert.deepEqual(estimateForecast([...points, { date: '2020-01-01', rate: 900 }], 301, [], now), high, 'Old observations must not enter the trailing year.');
assert.throws(() => estimateForecast(points, 0, [], now));
assert.throws(() => estimateForecast(points.slice(-10), 300, [], now));
const windows = forecastWindows(Date.parse('2026-12-31T16:30:00Z'));
assert.equal(new Date(windows[0].start * DAY).toISOString().slice(0, 10), '2027-01-01', 'Calendar dates must use Kuala Lumpur.');
assert.equal(new Date(windows[2].end * DAY).toISOString().slice(0, 10), '2027-04-30');
const leap = forecastWindows(Date.parse('2024-02-10T12:00:00+08:00'));
assert.equal(new Date(leap[0].end * DAY).toISOString().slice(0, 10), '2024-02-29');
assert.equal(formatForecastPercent(0.05), '<1%');
assert.equal(formatForecastPercent(99.95), '>99%');
// Historical paths must give no greater chance when the target rises.
const varying = points.map((p, i) => ({ ...p, rate: 300 + Math.sin(i / 5) * 10 }));
const lower = estimateForecast(varying, 305, [], now);
const higher = estimateForecast(varying, 315, [], now);
assert.ok(lower.windows.every((w, i) => Number.isFinite(w.percent) && w.percent >= higher.windows[i].percent && Math.abs(w.hits / w.paths * 100 - w.percent) < 1e-10));
assert.ok(lower.windows[2].percent >= lower.windows[1].percent);
console.log('Forecast checks passed: deterministic paths, target monotonicity, exact fractions, calendar boundaries, history cutoffs, input errors, and zero/all-hit cases.');
